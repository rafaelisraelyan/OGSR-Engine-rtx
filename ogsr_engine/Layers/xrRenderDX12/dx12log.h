#pragma once

// F2.1-B.1: минимальный файловый логгер для smoke-приложения.
//
// Приложение собрано с SubSystem=Windows, поэтому stdout при запуске без
// консоли не виден. Лог пишется рядом с exe и читается после запуска.
//
// Ограничения (сознательные):
//   - нет уровней, фильтров и ротации: на объём smoke-теста это не нужно;
//   - нет буферизации в отдельном потоке: однопоточное приложение;
//   - запись в лог НИКОГДА не влияет на результат рендеринга: сбой fopen
//     молча отключает лог, рендер продолжается;
//   - не логируются секреты и пользовательские данные — только диагностика DX12.

#include <cstdarg>
#include <cstdio>

namespace dx12log
{
    // Открывает (или переоткрывает) файл лога. Путь рядом с модулем.
    // Повторный вызов безопасен: предыдущий файл закрывается.
    // Возвращает false, если файл открыть не удалось (лог отключён).
    bool Open();

    // Закрывает файл лога. Идемпотентен.
    void Close();

    // Пишет строку с временной меткой. Если лог не открыт — вызов бесплатен.
    void Write(const char* fmt, ...);

    // Пишет широкую строку (описания GPU, пути). Конвертируется в UTF-8.
    void WriteWide(const wchar_t* fmt, ...);

    // Текущий путь к файлу лога (пустая строка, если лог отключён).
    const wchar_t* Path();
}
